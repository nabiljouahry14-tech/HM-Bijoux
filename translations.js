// Get translation
function t(key, lang = window.currentLanguage || 'en') {
  let text = translations[lang]?.[key] || translations['en'][key] || key;
  
  // Replace placeholders
  text = text.replace('{year}', new Date().getFullYear());
  
  return text;
}

// Get currency symbol
function getCurrencySymbol(lang = window.currentLanguage || 'en') {
  return t('currency.symbol', lang);
}

// Format currency with symbol position based on language
function formatCurrency(value, lang = window.currentLanguage || 'en') {
  const symbol = getCurrencySymbol(lang);
  const amount = Number(value || 0).toFixed(2);
  if (lang === 'ar') {
    return `${amount} ${symbol}`;
  }
  return `${symbol} ${amount}`;
}

// Set language and update DOM
function setLanguage(lang) {
  window.currentLanguage = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  localStorage.setItem('language', lang);
  
  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key, lang);
  });
  
  // Update all placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key, lang);
  });
  
  // Dispatch custom event so other scripts know language changed
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
  const savedLanguage = localStorage.getItem('language') || 'en';
  setLanguage(savedLanguage);

});
